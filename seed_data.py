# ── helpers ──────────────────────────────────────────────────────────────────
def spot(grain, dm, sym, basis):
    return {"id": f"SPOT_{grain[:2].upper()}", "grain": grain, "deliveryMonth": dm,
            "futuresSymbol": sym, "basisCents": basis, "isSpot": True, "spotGrain": grain}

def row(rid, grain, dm, sym, basis):
    return {"id": rid, "grain": grain, "deliveryMonth": dm,
            "futuresSymbol": sym, "basisCents": basis, "isSpot": False}

