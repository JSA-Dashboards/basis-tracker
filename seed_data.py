# ── Mendota helper to build a full timestamp block ────────────────────────────
def mendota_snap(ts, loc, spots_dict, rows_list):
    spot_rows = [
        spot(g, s["dm"], s["sym"], s["basis"])
        for g, s in spots_dict.items()
    ]
    return {"timestamp": ts, "provider": "Mendota", "location": loc,
            "rows": spot_rows + rows_list}

